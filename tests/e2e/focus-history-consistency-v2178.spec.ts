import { expect, test, type Page } from '@playwright/test'
import { startV217, testHabit, databaseCall, openHabit, nav } from '../helpers/v217Harness'

test.use({ timezoneId: 'Asia/Shanghai' })
async function seed(page: Page, count: number) {
  await startV217(page, { habits: [testHabit('一致性')], start: '05:00' })
  await databaseCall(page, `await db.saveFocusSessions(Array.from({length:${count}},(_,i)=>({id:'history-'+i,context:{kind:'habit',habitId:'一致性'},mode:'stopwatch',tagIds:['default'],startedAt:new Date(Date.UTC(2026,9,20,18,i)).toISOString(),endedAt:new Date(Date.UTC(2026,9,20,18,i+1)).toISOString(),durationSeconds:60,createdAt:'2026-10-01T00:00:00Z',updatedAt:'2026-10-01T00:00:00Z'})))`)
  await page.reload()
  const detail = await openHabit(page, '一致性')
  await detail.locator('.ui-focus-card-history').click()
  return page.getByRole('region', { name: '习惯专注历史' })
}

test('1000 real records render 20 at a time, navigate, edit and correct deletion boundaries', async ({ page }) => {
  const history = await seed(page, 1000)
  await expect(history.locator('.focus-history-item')).toHaveCount(20)
  await expect(history.locator('.focus-history-summary')).toContainText('1000 条记录')
  await expect(history.getByRole('navigation')).toContainText('1 / 50')
  await expect(history.getByRole('button', { name: '上一页' })).toBeDisabled()
  for (let i = 1; i < 50; i++) await history.getByRole('button', { name: '下一页' }).click()
  await expect(history.getByRole('navigation')).toContainText('50 / 50')
  await expect(history.getByRole('button', { name: '下一页' })).toBeDisabled()
  await history.getByRole('button', { name: '更改', exact: true }).last().click()
  const editor = page.getByRole('dialog', { name: '修改习惯专注记录' })
  await editor.getByLabel('结束', { exact: true }).fill('2026-10-21T02:02')
  await editor.getByRole('button', { name: '保存修改' }).click()
  await expect(editor).toBeHidden()
  await expect(history.locator('.focus-history-item').last()).toContainText('2分钟')
  page.on('dialog', dialog => dialog.accept())
  for (let i = 0; i < 20; i++) await history.getByRole('button', { name: '删除', exact: true }).last().click()
  await expect(history.getByRole('navigation')).toContainText('49 / 49')
  await expect(history.locator('.focus-history-item')).toHaveCount(20)
  await history.getByRole('button', { name: '上一页' }).click()
  await expect(history.getByRole('navigation')).toContainText('48 / 49')
  await expect.poll(() => databaseCall<any[]>(page, 'return (await db.loadFocusSessions()).filter(s=>!s.trashedAt)')).toHaveLength(980)
  await history.getByRole('button', { name: '‹ 返回完成日历' }).click()
  await expect(page.locator('.habit-calendar')).toBeVisible()
  await expect(page.locator('.habit-focus-panel')).toContainText('16小时20分钟')
})

for (const width of [320,375,390,430]) test(`history and edit dialog fit ${width}px and dates follow global preference`, async ({page}) => {
  await page.setViewportSize({width,height:740})
  const history = await seed(page, 21)
  const before = await history.locator('.focus-history-meta span').first().innerText()
  await history.getByRole('button',{name:'‹ 返回完成日历'}).click()
  await page.getByRole('dialog',{name:'一致性详情'}).locator('header button').click()
  await nav(page,'设置')
  await page.getByRole('button', {name:'Sep 22, 2026',exact:true}).click()
  await openHabit(page,'一致性')
  await page.locator('.habit-focus-panel .ui-focus-card-history').click()
  const after = await history.locator('.focus-history-meta span').first().innerText()
  expect(after).not.toBe(before)
  expect(after).toContain('Oct 21, 2026')
  const bounds = await history.evaluate(el => ({scroll:el.scrollWidth,width:el.clientWidth,right:el.getBoundingClientRect().right,viewport:innerWidth}))
  expect(bounds.scroll).toBeLessThanOrEqual(bounds.width+1)
  expect(bounds.right).toBeLessThanOrEqual(bounds.viewport)
  await history.getByRole('button',{name:'更改',exact:true}).first().click()
  const editor = page.getByRole('dialog',{name:'修改习惯专注记录'})
  await expect(editor.getByRole('button',{name:'保存修改'})).toBeInViewport()
  expect(await editor.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true)
  await editor.getByRole('button',{name:'取消',exact:true}).click()
  await expect(history.locator('.focus-history-item')).toHaveCount(20)
})

test('task, habit and note histories present matching totals, record hierarchy and outlined actions', async ({page}) => {
  const habit = await seed(page,1)
  async function inspect(root: ReturnType<Page['locator']>) {
    await expect(root.getByRole('heading',{name:/专注历史/})).toBeVisible()
    await expect(root.locator('.focus-history-summary')).toContainText('1 条记录')
    await expect(root.locator('.focus-history-meta')).toContainText('1分钟')
    await expect(root.getByRole('button',{name:'更改',exact:true})).toBeVisible()
    await expect(root.getByRole('button',{name:'删除',exact:true})).toBeVisible()
    return root.locator('.focus-history-item').evaluate(el=>{
      const style = getComputedStyle(el)
      const actions = [...el.querySelectorAll('.focus-history-actions button')].map(b=>{const s=getComputedStyle(b);return {background:s.backgroundColor,color:s.color,border:s.borderTopStyle,borderColor:s.borderTopColor,radius:s.borderRadius}})
      return {border:style.borderTopStyle,radius:style.borderRadius,actions}
    })
  }
  const expected = await inspect(habit)
  await habit.getByRole('button',{name:'‹ 返回完成日历'}).click()
  await page.getByRole('dialog',{name:'一致性详情'}).locator('header button').click()
  await databaseCall(page, `const stamp='2026-10-21T02:00:00+08:00';await db.saveNotes([{id:'note',notebookId:'default',title:'笔记对照',content:'',active:true,tagIds:['default'],createdAt:stamp,updatedAt:stamp}]);await db.saveTasks([{id:'task',title:'任务对照',date:'2026-10-25',priority:0,allDay:true,status:'todo',tagIds:['default'],createdAt:stamp,updatedAt:stamp}]);const [s]=await db.loadFocusSessions();await db.saveFocusSessions([s,...['task','note'].map(kind=>({...s,id:kind,context:kind==='task'?{kind,taskId:'task'}:{kind,noteId:'note'}}))]);`)
  await page.reload()
  await nav(page,'笔记')
  await page.locator('.note-row').filter({hasText:'笔记对照'}).click()
  await page.locator('.note-focus-card .ui-focus-card-history').click()
  const note = page.getByRole('dialog',{name:'笔记专注历史',exact:true})
  expect(await inspect(note)).toEqual(expected)
  await note.getByRole('button',{name:'返回',exact:true}).click()
  await page.locator('.note-editor').getByRole('button',{name:'完成',exact:true}).click()
  await nav(page,'日历')
  await page.locator('.continuous-calendar .day-cell.today').first().click()
  await page.locator('.day-drawer').getByText('任务对照',{exact:true}).click()
  const task=page.locator('.task-viewer')
  await task.locator('.ui-focus-card-history').click()
  expect(await inspect(task)).toEqual(expected)
})

test('empty history returns to calendar and focus timing still updates totals without check-ins', async ({page})=>{
  const history=await seed(page,0)
  await expect(history.getByText('还没有专注记录',{exact:true})).toBeVisible()
  await expect(history.locator('.focus-history-summary')).toContainText('0 条记录')
  await history.getByRole('button',{name:'‹ 返回完成日历'}).click()
  await page.getByRole('button',{name:'▶ 开始习惯专注',exact:true}).click()
  await page.clock.runFor(65000)
  await page.getByRole('button',{name:'结束专注',exact:true}).click()
  await expect(page.locator('.habit-focus-panel')).toContainText('1分钟')
  await page.locator('.habit-focus-panel .ui-focus-card-history').click()
  await expect(history.locator('.focus-history-item')).toHaveCount(1)
  const sessions=await databaseCall<any[]>(page,'return await db.loadFocusSessions()')
  expect(sessions[0].context).toEqual({kind:'habit',habitId:'一致性'})
  expect(sessions[0].durationSeconds).toBeGreaterThanOrEqual(65)
  expect(await databaseCall(page,'return await db.loadHabitCheckIns()')).toEqual([])
})
